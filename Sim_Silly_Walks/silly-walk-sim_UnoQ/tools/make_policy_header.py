"""Make the C header for the STM32 from model_499.pt, using only the Python standard library.

Writes:
  sketch/policy_weights.h          normalizer mean/std + all actor weights (float32)
  sketch/policy_test_vectors.h     20 fixed test observations (only the step 5 test sketch uses it)
  tools/policy_test_vectors.json   the same observations + the expected actions (pure-Python reference)

Run from the app folder:  python3 tools/make_policy_header.py [model_499.pt]
"""
import json
import math
import random
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import ptload  # noqa: E402

APP = Path(__file__).resolve().parent.parent
EPS = 0.01        # rsl_rl EmpiricalNormalization eps
N_TESTS = 20


def f32(x):
    """Round a Python float to float32, like the STM32 will store it."""
    return struct.unpack("<f", struct.pack("<f", x))[0]


def load_actor(path):
    sd = ptload.load(path)["actor_state_dict"]
    g = lambda k: sd[k]
    return {
        "mean": g("obs_normalizer._mean").data, "std": g("obs_normalizer._std").data,
        "W0": g("mlp.0.weight").rows(), "b0": g("mlp.0.bias").data,
        "W1": g("mlp.2.weight").rows(), "b1": g("mlp.2.bias").data,
        "W2": g("mlp.4.weight").rows(), "b2": g("mlp.4.bias").data,
    }


def reference(p, obs):
    """Pure-Python forward pass (float64 math on float32 weights)."""
    elu = lambda v: v if v > 0 else math.expm1(v)
    x = [(o - m) / (s + EPS) for o, m, s in zip(obs, p["mean"], p["std"])]
    for W, b, act in ((p["W0"], p["b0"], True), (p["W1"], p["b1"], True), (p["W2"], p["b2"], False)):
        y = [sum(w * xi for w, xi in zip(row, x)) + bi for row, bi in zip(W, b)]
        x = [elu(v) for v in y] if act else y
    return x


def c_array(name, values, per_line=8):
    vals = [f"{f32(v):.9g}f" for v in values]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f"const float {name}[{len(values)}] = {{\n  " + ",\n  ".join(lines) + "\n};\n"


def main():
    ckpt = sys.argv[1] if len(sys.argv) > 1 else str(APP / "model_499.pt")
    p = load_actor(ckpt)
    n_obs, n_hid, n_act = len(p["mean"]), len(p["b0"]), len(p["b2"])
    assert (n_obs, n_hid, n_act) == (7, 64, 2), (n_obs, n_hid, n_act)
    flat = lambda rows: [v for r in rows for v in r]

    h = [
        "// AUTO-GENERATED by tools/make_policy_header.py from " + Path(ckpt).name + " - do not edit by hand.",
        "// Actor of the Drive-Straight policy: obs(7) -> normalize -> 64 -> ELU -> 64 -> ELU -> 2.",
        "// Weights are row-major [out][in], like PyTorch's nn.Linear.weight.",
        "#pragma once",
        "",
        f"#define POLICY_OBS {n_obs}",
        f"#define POLICY_HID {n_hid}",
        f"#define POLICY_ACT {n_act}",
        f"#define POLICY_NORM_EPS {EPS}f   // rsl_rl EmpiricalNormalization: (obs - mean) / (std + eps)",
        "",
        "// Observation order: ang_vel x,y,z (rad/s, body) | sin(yaw), cos(yaw) | previous action L, R",
        c_array("POLICY_OBS_MEAN", p["mean"]),
        c_array("POLICY_OBS_STD", p["std"]),
        c_array("POLICY_W0", flat(p["W0"])), c_array("POLICY_B0", p["b0"]),
        c_array("POLICY_W1", flat(p["W1"])), c_array("POLICY_B1", p["b1"]),
        c_array("POLICY_W2", flat(p["W2"])), c_array("POLICY_B2", p["b2"]),
    ]
    (APP / "sketch" / "policy_weights.h").write_text("\n".join(h))

    # Test observations: random values spread like the training data (mean +- 1.5 std), fixed seed.
    rng = random.Random(1234)
    tests = []
    for _ in range(N_TESTS):
        obs = [f32(m + s * rng.uniform(-1.5, 1.5)) for m, s in zip(p["mean"], p["std"])]
        yaw = rng.uniform(-0.6, 0.6)                    # make sin/cos a consistent pair
        obs[3], obs[4] = f32(math.sin(yaw)), f32(math.cos(yaw))
        tests.append({"obs": obs, "action": reference(p, obs)})
    (APP / "tools" / "policy_test_vectors.json").write_text(json.dumps(tests, indent=1))

    t = ["// AUTO-GENERATED by tools/make_policy_header.py - test observations for the step 5 check.",
         "#pragma once", f"#define N_POLICY_TESTS {N_TESTS}",
         "const float POLICY_TEST_OBS[N_POLICY_TESTS][POLICY_OBS] = {"]
    t += ["  {" + ", ".join(f"{v:.9g}f" for v in x["obs"]) + "}," for x in tests]
    t += ["};", ""]
    (APP / "sketch" / "policy_test_vectors.h").write_text("\n".join(t))
    print(f"wrote sketch/policy_weights.h, sketch/policy_test_vectors.h, tools/policy_test_vectors.json "
          f"({n_obs}->{n_hid}->{n_hid}->{n_act}, {N_TESTS} test vectors)")


if __name__ == "__main__":
    main()
